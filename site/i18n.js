  function get() {
    var l = localStorage.getItem(LS_KEY);
    return (l === 'ua' || l === 'en') ? l : 'en';
  }

  function lookup(key, lang) {
    var dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
    if (Object.prototype.hasOwnProperty.call(dict, key)) return dict[key];
    if (Object.prototype.hasOwnProperty.call(TRANSLATIONS.en, key)) return TRANSLATIONS.en[key];
    return null;
  }

  function t(key, lang) {
    var v = lookup(key, lang || get());
    return v == null ? key : v;
  }

  function apply(lang) {
    lang = (lang === 'ua' || lang === 'en') ? lang : get();
    document.documentElement.lang = lang;

    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var v = lookup(el.getAttribute('data-i18n'), lang);
      if (v != null) el.textContent = v;
    });
    document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
      var v = lookup(el.getAttribute('data-i18n-html'), lang);
      if (v != null) el.innerHTML = v;
    });
    document.querySelectorAll('[data-i18n-ph]').forEach(function (el) {
      var v = lookup(el.getAttribute('data-i18n-ph'), lang);
      if (v != null) el.setAttribute('placeholder', v);
    });

    // Reflect active state on any visible toggle (e.g. index navbar)
    document.querySelectorAll('[data-lang-btn]').forEach(function (btn) {
      btn.classList.toggle('active', btn.getAttribute('data-lang-btn') === lang);
    });

    try {
      document.dispatchEvent(new CustomEvent('fitai:langchange', { detail: { lang: lang } }));
    } catch (e) { /* old browsers — non-fatal */ }
  }

  function set(lang) {
    lang = (lang === 'ua' || lang === 'en') ? lang : 'en';
    localStorage.setItem(LS_KEY, lang);
    apply(lang);
    return lang;
  }

  function toggle() {
    return set(get() === 'en' ? 'ua' : 'en');
  }

  window.FitAILang = { get: get, set: set, toggle: toggle, apply: apply, t: t, TRANSLATIONS: TRANSLATIONS };

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', function () { apply(get()); });
  } else {
    apply(get());
  }
